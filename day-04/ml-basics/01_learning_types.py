# Machine Learning Learning Types

print("===== Supervised Learning =====")
print("Supervised learning uses labeled data.")
print("The model learns from input data and known output.")
print("Examples: predicting salary, classifying Pass or Fail.")

print("\n===== Unsupervised Learning =====")
print("Unsupervised learning uses data without labeled output.")
print("The model finds patterns or groups in the data.")
print("Example: grouping customers based on their behavior.")

print("\n===== Simple Difference =====")
print("Supervised   -> Data + Correct Output")
print("Unsupervised -> Data without Correct Output")